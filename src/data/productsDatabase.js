// Fallback lookup generator for missing categories or conditions
export function getProductsForCondition(conditionName = 'Healthy Skin') {
  const normalized = conditionName || 'Healthy Skin'
  // Direct match or partial key match
  const matchedKey = Object.keys(PRODUCTS_DATABASE).find(
    (key) => key.toLowerCase() === normalized.toLowerCase()
  )

  if (matchedKey && PRODUCTS_DATABASE[matchedKey]) {
    return PRODUCTS_DATABASE[matchedKey]
  }

  // Fallback default catalog if condition is not directly listed
  return PRODUCTS_DATABASE['Acne']
}
